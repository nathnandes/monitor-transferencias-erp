from enum import StrEnum


class Aba(StrEnum):
    DASHBOARD_TV = "DASHBOARD.TV"
    TRANSFERENCIAS_CONTROLE = "TRANSFERENCIAS.CONTROLE"
    ESTOQUE_SALDOS = "ESTOQUE.SALDOS"
    ESTOQUE_LOJA = "ESTOQUE.LOJA"
    ESTOQUE_LIVRO = "ESTOQUE.LIVRO"
    ESTOQUE_BALANCO = "ESTOQUE.BALANCO"
    ESTOQUE_AVULSAS = "ESTOQUE.AVULSAS"
    ESTOQUE_JUSTIFICATIVAS = "ESTOQUE.JUSTIFICATIVAS"
    VENDAS_TV = "VENDAS.TV"

    VENDAS_GERAL = "VENDAS.GERAL"
    VENDAS_EMPRESA_1 = "VENDAS.EMPRESA_1"
    VENDAS_EMPRESA_2 = "VENDAS.EMPRESA_2"
    VENDAS_EMPRESA_3 = "VENDAS.EMPRESA_3"
    VENDAS_EMPRESA_6 = "VENDAS.EMPRESA_6"


def modulo_da_aba(aba: Aba) -> str:
    return aba.split(".", 1)[0]


